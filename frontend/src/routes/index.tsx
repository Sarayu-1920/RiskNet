import { createFileRoute, Link } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { ArrowUpRight } from "lucide-react";
import { AppShell } from "@/components/layout/AppShell";
import { Panel, StatCard } from "@/components/common/Panel";
import { RiskBadge, RiskScore, StatusBadge } from "@/components/common/Badges";
import { EmptyState, ErrorState, LoadingState } from "@/components/common/DataStates";
import { getAlerts } from "@/services/api";
import { humanize, relativeTime } from "@/lib/format";
import type { RiskLevel } from "@/types/risknet";

export const Route = createFileRoute("/")({
  head: () => ({
    meta: [
      { title: "Dashboard · RiskNet Fraud Investigation" },
      {
        name: "description",
        content:
          "Analyst dashboard for RiskNet: alert volume, high-risk exposure and in-progress fraud investigations.",
      },
      { property: "og:title", content: "Dashboard · RiskNet Fraud Investigation" },
      {
        property: "og:description",
        content: "Alert volume, risk overview and active fraud investigations at a glance.",
      },
    ],
  }),
  component: DashboardPage,
});

const levels: RiskLevel[] = ["CRITICAL", "HIGH", "MEDIUM", "LOW"];
const levelBar: Record<RiskLevel, string> = {
  CRITICAL: "bg-risk-critical",
  HIGH: "bg-risk-high",
  MEDIUM: "bg-risk-medium",
  LOW: "bg-risk-low",
};

function DashboardPage() {
  const { data, isPending, isError, refetch } = useQuery({
    queryKey: ["alerts", {}],
    queryFn: () => getAlerts(),
  });

  const alerts = data ?? [];
  const total = alerts.length;
  const open = alerts.filter((a) => a.status === "OPEN").length;
  const highRisk = alerts.filter((a) => a.riskLevel === "HIGH" || a.riskLevel === "CRITICAL").length;
  const inProgress = alerts.filter(
    (a) => a.status === "IN_PROGRESS" || a.status === "ESCALATED",
  ).length;
  const recent = [...alerts]
    .sort((a, b) => +new Date(b.generatedAt) - +new Date(a.generatedAt))
    .slice(0, 6);

  return (
    <AppShell title="Dashboard" subtitle="Live fraud alert posture across the applicant portfolio">
      {isPending ? (
        <LoadingState label="Loading alert metrics…" />
      ) : isError ? (
        <ErrorState onRetry={() => refetch()} />
      ) : (
        <div className="space-y-5">
          <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
            <StatCard label="Total alerts" value={total} hint="All statuses" />
            <StatCard label="Open alerts" value={open} hint="Awaiting triage" tone="primary" />
            <StatCard label="High-risk alerts" value={highRisk} hint="HIGH + CRITICAL" tone="critical" />
            <StatCard
              label="In-progress investigations"
              value={inProgress}
              hint="Assigned or escalated"
              tone="high"
            />
          </div>

          <div className="grid gap-5 xl:grid-cols-[2fr_1fr]">
            <Panel
              title="Recent alerts"
              description="Newest signals generated by the risk engine"
              bodyClassName="p-0"
              actions={
                <Link
                  to="/alerts"
                  className="inline-flex items-center gap-1 text-xs font-medium text-primary hover:underline"
                >
                  View all alerts <ArrowUpRight className="size-3.5" aria-hidden />
                </Link>
              }
            >
              {recent.length === 0 ? (
                <div className="p-4">
                  <EmptyState title="No alerts returned" />
                </div>
              ) : (
                <ul className="divide-y divide-border">
                  {recent.map((alert) => (
                    <li key={alert.alertId}>
                      <Link
                        to="/alerts/$alertId"
                        params={{ alertId: alert.alertId }}
                        className="flex flex-wrap items-center gap-3 px-4 py-3 transition-colors hover:bg-accent/40"
                      >
                        <span className="mono w-24 text-xs text-primary">{alert.alertId}</span>
                        <span className="min-w-0 flex-1">
                          <span className="mono block truncate text-sm text-foreground">
                            {alert.applicantId}
                          </span>
                          <span className="block text-xs text-muted-foreground">
                            {humanize(alert.alertType)} · {relativeTime(alert.generatedAt)}
                          </span>
                        </span>
                        <RiskScore score={alert.riskScore} level={alert.riskLevel} />
                        <RiskBadge level={alert.riskLevel} />
                        <StatusBadge status={alert.status} />
                      </Link>
                    </li>
                  ))}
                </ul>
              )}
            </Panel>

            <Panel title="Risk overview" description="Alert distribution by risk level">
              <ul className="space-y-4">
                {levels.map((level) => {
                  const count = alerts.filter((a) => a.riskLevel === level).length;
                  const pct = total ? Math.round((count / total) * 100) : 0;
                  return (
                    <li key={level}>
                      <div className="flex items-center justify-between text-xs">
                        <span className="font-medium text-foreground">{level}</span>
                        <span className="mono text-muted-foreground">
                          {count} · {pct}%
                        </span>
                      </div>
                      <span className="mt-1.5 block h-2 w-full overflow-hidden rounded-full bg-secondary">
                        <span
                          className={`block h-full rounded-full ${levelBar[level]}`}
                          style={{ width: `${pct}%` }}
                        />
                      </span>
                    </li>
                  );
                })}
              </ul>
              <p className="mt-5 border-t border-border pt-3 text-xs text-muted-foreground">
                Highest observed score:{" "}
                <span className="mono text-foreground">
                  {alerts.reduce((m, a) => Math.max(m, a.riskScore), 0)}
                </span>
              </p>
            </Panel>
          </div>
        </div>
      )}
    </AppShell>
  );
}
